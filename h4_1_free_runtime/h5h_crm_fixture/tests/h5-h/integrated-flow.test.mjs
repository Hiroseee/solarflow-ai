test('K-M PDFKit generated bytes, immutable checksums and preserved history',async()=>{
 const j=new IntegratedFixtureJourney(),r=await j.record(request());
 const pdf=await j.pdf('fictional_budget','r1');
 assert.equal(pdf.subarray(0,5).toString(),'%PDF-');
 assert.equal(createHash('sha256').update(pdf).digest('hex'),r.pdfSha256);
 assert.equal(r.state,'FIXTURE_STORED_NOT_ISSUED');
 await j.record(request(complete(),'r2','m2'));
 assert.deepEqual(j.list('fictional_budget').map(x=>x.revisionId),['r1','r2']);
});
