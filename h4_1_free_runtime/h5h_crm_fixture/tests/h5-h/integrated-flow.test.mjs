const empty=()=>({client:'Cliente fictício H5-H',kitChoice:null,items:[],pricing:{unitPrices:{},freight:{incoterm:'FOB',mode:'none'}}});
function complete(){
 let d=chooseKit(empty(),'12kw');
 for(const [productId,quantity,lineId,relatedBessLineId] of [
  ['fixture-inv-12',1,'inv'],['fixture-bess',1,'bess'],['fixture-module',8,'mod'],
  ['fixture-accessory',2,'acc','bess'],['fixture-cable',10,'cable'],['fixture-mc4',2,'mc4']
 ])d=addItem(d,fictionalCatalog,{productId,quantity,lineId,relatedBessLineId});
 return {...d,pricing:{unitPrices:{'fixture-inv-12':100000,'fixture-bess':700000,
  'fixture-module':15000,'fixture-accessory':2000,'fixture-cable':200,'fixture-mc4':500},
  freight:{incoterm:'CIF',mode:'manual',cents:12500}}};
}
const request=(d=complete(),revisionId='r1',mutationId='m1')=>({
 budgetId:'fictional_budget',revisionId,mutationId,version:2,draft:d
});
const start=async(t)=>{
 const server=createIntegratedFixtureServer();
 await new Promise(ok=>server.listen(0,'127.0.0.1',ok));
 t.after(()=>new Promise(ok=>server.close(ok)));
 return 'http://127.0.0.1:'+server.address().port;
};
